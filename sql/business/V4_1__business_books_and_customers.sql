-- 生意账本独立业务空间，仅复用公共账号身份，不关联家庭业务。
CREATE SCHEMA IF NOT EXISTS business;

CREATE TABLE business.biz_book (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  request_id VARCHAR(80) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(created_by, request_id)
);
CREATE TABLE business.biz_member (
  book_id BIGINT NOT NULL REFERENCES business.biz_book(id),
  user_id INTEGER NOT NULL REFERENCES relations.sys_user(id),
  role VARCHAR(10) NOT NULL CHECK(role IN ('owner', 'member')),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(book_id, user_id)
);
CREATE INDEX idx_biz_member_user ON business.biz_member(user_id, book_id);

CREATE TABLE business.biz_customer (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL REFERENCES business.biz_book(id),
  type VARCHAR(10) NOT NULL CHECK(type IN ('farmer', 'merchant')),
  name VARCHAR(30) NOT NULL,
  appellation VARCHAR(30) NOT NULL DEFAULT '',
  phone VARCHAR(30) NOT NULL DEFAULT '',
  remark VARCHAR(200) NOT NULL DEFAULT '',
  request_id VARCHAR(80) NOT NULL,
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(book_id, request_id),
  UNIQUE(book_id, id)
);
CREATE INDEX idx_biz_customer_book_type ON business.biz_customer(book_id, type, created_at, id);

COMMENT ON TABLE business.biz_book IS '独立生意账套';
COMMENT ON COLUMN business.biz_book.id IS '生意账套编号';
COMMENT ON COLUMN business.biz_book.name IS '账套名称';
COMMENT ON COLUMN business.biz_book.created_by IS '创建账号，不关联家庭';
COMMENT ON COLUMN business.biz_book.request_id IS '创建请求幂等编号';
COMMENT ON COLUMN business.biz_book.created_at IS '创建时间';
COMMENT ON TABLE business.biz_member IS '生意账套成员，仅在生意边界内授权';
COMMENT ON COLUMN business.biz_member.book_id IS '所属生意账套';
COMMENT ON COLUMN business.biz_member.user_id IS '公共登录账号编号';
COMMENT ON COLUMN business.biz_member.role IS '账套角色，owner创建者、member成员';
COMMENT ON COLUMN business.biz_member.created_at IS '加入时间';
COMMENT ON TABLE business.biz_customer IS '生意往来客户，包括农户、供应商及粮商';
COMMENT ON COLUMN business.biz_customer.id IS '客户编号';
COMMENT ON COLUMN business.biz_customer.book_id IS '所属生意账套';
COMMENT ON COLUMN business.biz_customer.type IS '客户类型，farmer农户、merchant商家';
COMMENT ON COLUMN business.biz_customer.name IS '客户姓名或商家名称';
COMMENT ON COLUMN business.biz_customer.appellation IS '称谓，选填';
COMMENT ON COLUMN business.biz_customer.phone IS '联系电话，选填';
COMMENT ON COLUMN business.biz_customer.remark IS '备注，选填';
COMMENT ON COLUMN business.biz_customer.request_id IS '创建请求幂等编号';
COMMENT ON COLUMN business.biz_customer.created_by IS '记录人账号';
COMMENT ON COLUMN business.biz_customer.created_at IS '创建时间';
COMMENT ON COLUMN business.biz_customer.updated_at IS '最后修改时间';

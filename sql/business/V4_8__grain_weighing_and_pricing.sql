CREATE TABLE business.biz_grain_weighing (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES relations.sys_user(id),
  customer_id BIGINT NOT NULL,
  grain VARCHAR(10) NOT NULL CHECK (grain IN ('小麦','水稻')),
  gross_weight_kg NUMERIC(12,3) NOT NULL,
  tare_weight_kg NUMERIC(12,3) NOT NULL CHECK (tare_weight_kg >= 0),
  biz_date DATE NOT NULL,
  remark VARCHAR(200) NOT NULL DEFAULT '',
  trade_id BIGINT,
  request_id VARCHAR(80) NOT NULL,
  request_payload TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (gross_weight_kg > tare_weight_kg),
  UNIQUE (owner_id,request_id),
  FOREIGN KEY (owner_id,customer_id) REFERENCES business.biz_customer(owner_id,id),
  FOREIGN KEY (owner_id,customer_id,trade_id) REFERENCES business.biz_trade(owner_id,customer_id,id)
);
CREATE INDEX idx_biz_grain_pending ON business.biz_grain_weighing(owner_id,customer_id,trade_id,id);

ALTER TABLE business.biz_settlement ADD COLUMN request_id VARCHAR(80);
ALTER TABLE business.biz_settlement ADD COLUMN request_payload TEXT;
ALTER TABLE business.biz_settlement ADD CONSTRAINT uq_biz_settlement_request UNIQUE(owner_id,request_id);

COMMENT ON TABLE business.biz_grain_weighing IS '每车原始称重，未计价时不形成应付款；trade_id关联一次集中计价原单';
COMMENT ON COLUMN business.biz_grain_weighing.trade_id IS '已计价收粮原单，未计价为空；称重原值保持不变';
COMMENT ON COLUMN business.biz_settlement.request_payload IS '独立付款的提交内容，用于幂等和重试冲突校验';

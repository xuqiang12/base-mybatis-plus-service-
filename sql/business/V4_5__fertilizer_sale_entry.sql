CREATE TABLE business.biz_product (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES relations.sys_user(id),
  name VARCHAR(50) NOT NULL,
  bag_weight_kg NUMERIC(9,3) NOT NULL CHECK(bag_weight_kg > 0),
  sale_price NUMERIC(11,2) NOT NULL CHECK(sale_price > 0),
  request_id VARCHAR(80) NOT NULL,
  request_payload TEXT NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(owner_id,id),
  UNIQUE(owner_id,request_id)
);
CREATE INDEX idx_biz_product_owner ON business.biz_product(owner_id,deleted_at,id);

CREATE TABLE business.biz_account (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES relations.sys_user(id),
  name VARCHAR(30) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(owner_id,id),
  UNIQUE(owner_id,name)
);


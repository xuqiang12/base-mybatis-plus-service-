-- 客户未结款查询的数据来源。买卖、结算写入接口在对应功能阶段实现。
CREATE TABLE business.biz_trade (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL,
  customer_id BIGINT NOT NULL,
  direction VARCHAR(10) NOT NULL CHECK(direction IN ('sale', 'purchase')),
  biz_date DATE NOT NULL,
  season VARCHAR(50) NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'posted' CHECK(status IN ('posted', 'void')),
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(book_id, customer_id) REFERENCES business.biz_customer(book_id, id),
  UNIQUE(book_id, customer_id, id)
);
CREATE TABLE business.biz_trade_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL,
  customer_id BIGINT NOT NULL,
  trade_id BIGINT NOT NULL,
  category VARCHAR(15) NOT NULL CHECK(category IN ('fertilizer', 'grain')),
  product_name VARCHAR(100) NOT NULL,
  quantity NUMERIC(20,6) NOT NULL CHECK(quantity > 0),
  unit VARCHAR(10) NOT NULL,
  unit_price NUMERIC(20,6) NOT NULL CHECK(unit_price >= 0),
  bag_weight_kg NUMERIC(20,6) CHECK(bag_weight_kg > 0),
  amount_cents BIGINT NOT NULL CHECK(amount_cents > 0 AND amount_cents <= 9007199254740991),
  FOREIGN KEY(book_id, customer_id, trade_id) REFERENCES business.biz_trade(book_id, customer_id, id),
  UNIQUE(book_id, customer_id, id)
);
CREATE INDEX idx_biz_trade_customer ON business.biz_trade(book_id, customer_id, biz_date, id);
CREATE INDEX idx_biz_trade_item_customer ON business.biz_trade_item(book_id, customer_id, trade_id);

CREATE TABLE business.biz_settlement (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL,
  customer_id BIGINT NOT NULL,
  kind VARCHAR(10) NOT NULL CHECK(kind IN ('receive', 'pay', 'offset')),
  amount_cents BIGINT NOT NULL CHECK(amount_cents > 0 AND amount_cents <= 9007199254740991),
  biz_date DATE NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'posted' CHECK(status IN ('posted', 'void')),
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(book_id, customer_id) REFERENCES business.biz_customer(book_id, id),
  UNIQUE(book_id, customer_id, id)
);
CREATE TABLE business.biz_settlement_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL,
  customer_id BIGINT NOT NULL,
  settlement_id BIGINT NOT NULL,
  trade_item_id BIGINT NOT NULL,
  amount_cents BIGINT NOT NULL CHECK(amount_cents > 0 AND amount_cents <= 9007199254740991),
  FOREIGN KEY(book_id, customer_id, settlement_id) REFERENCES business.biz_settlement(book_id, customer_id, id),
  FOREIGN KEY(book_id, customer_id, trade_item_id) REFERENCES business.biz_trade_item(book_id, customer_id, id),
  UNIQUE(settlement_id, trade_item_id)
);
CREATE INDEX idx_biz_settlement_item_trade ON business.biz_settlement_item(book_id, customer_id, trade_item_id);


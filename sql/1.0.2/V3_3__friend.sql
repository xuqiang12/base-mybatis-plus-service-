-- 亲友档案表
CREATE TABLE relations.ledger_friend (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  name VARCHAR(30) NOT NULL,
  appellation VARCHAR(30) NOT NULL DEFAULT '',
  gender SMALLINT NOT NULL DEFAULT 0 CHECK (gender IN (0, 1, 2)),
  remark VARCHAR(200) NOT NULL DEFAULT '',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 按家庭查询亲友的索引
CREATE INDEX idx_ledger_friend_family
    ON relations.ledger_friend(family_id);

-- 表和字段说明
COMMENT ON TABLE relations.ledger_friend IS '亲友档案表';
COMMENT ON COLUMN relations.ledger_friend.id IS '亲友编号，自增主键';
COMMENT ON COLUMN relations.ledger_friend.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_friend.name IS '姓名';
COMMENT ON COLUMN relations.ledger_friend.appellation IS '称谓，如表哥、同事';
COMMENT ON COLUMN relations.ledger_friend.gender IS '性别：0未填写，1男，2女';
COMMENT ON COLUMN relations.ledger_friend.remark IS '备注';
COMMENT ON COLUMN relations.ledger_friend.created_at IS '创建时间';
COMMENT ON COLUMN relations.ledger_friend.updated_at IS '最后修改时间，由后端在修改时更新';
-- 账簿与人情流水；家庭 ID 沿用现有 ledger_family 的字符串 UUID。
CREATE TABLE relations.ledger_book (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  name VARCHAR(100) NOT NULL,
  date DATE,
  note VARCHAR(1000) NOT NULL DEFAULT '',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ledger_book_family ON relations.ledger_book(family_id);

CREATE TABLE relations.ledger_gift (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  event_type VARCHAR(20) NOT NULL,
  direction VARCHAR(10) NOT NULL CHECK(direction IN ('received', 'sent')),
  date DATE NOT NULL,
  name VARCHAR(100) NOT NULL,
  appellation VARCHAR(100) NOT NULL DEFAULT '',
  amount_cents BIGINT NOT NULL CHECK(amount_cents > 0 AND amount_cents <= 9007199254740991),
  note VARCHAR(1000) NOT NULL DEFAULT '',
  book_id BIGINT REFERENCES relations.ledger_book(id),
  friend_id BIGINT REFERENCES relations.ledger_friend(id),
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  created_by_name VARCHAR(100) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ledger_gift_family_date ON relations.ledger_gift(family_id, date);
CREATE INDEX idx_ledger_gift_friend ON relations.ledger_gift(family_id, friend_id);
CREATE INDEX idx_ledger_gift_book ON relations.ledger_gift(family_id, book_id);

COMMENT ON TABLE relations.ledger_book IS '礼账收礼账簿';
COMMENT ON TABLE relations.ledger_gift IS '礼账人情流水';
COMMENT ON COLUMN relations.ledger_book.id IS '账簿编号，自增主键';
COMMENT ON COLUMN relations.ledger_book.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_book.name IS '账簿名称';
COMMENT ON COLUMN relations.ledger_book.date IS '账簿日期';
COMMENT ON COLUMN relations.ledger_book.note IS '备注';
COMMENT ON COLUMN relations.ledger_book.created_at IS '创建时间';
COMMENT ON COLUMN relations.ledger_book.updated_at IS '最后修改时间';
COMMENT ON COLUMN relations.ledger_gift.id IS '人情流水编号，自增主键';
COMMENT ON COLUMN relations.ledger_gift.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_gift.event_type IS '事件类型';
COMMENT ON COLUMN relations.ledger_gift.direction IS '收礼或送礼方向';
COMMENT ON COLUMN relations.ledger_gift.date IS '业务日期';
COMMENT ON COLUMN relations.ledger_gift.name IS '姓名快照';
COMMENT ON COLUMN relations.ledger_gift.appellation IS '称谓快照';
COMMENT ON COLUMN relations.ledger_gift.amount_cents IS '金额，整数分';
COMMENT ON COLUMN relations.ledger_gift.note IS '备注';
COMMENT ON COLUMN relations.ledger_gift.book_id IS '收礼账簿关联，可空';
COMMENT ON COLUMN relations.ledger_gift.friend_id IS '亲友关联，可空';
COMMENT ON COLUMN relations.ledger_gift.created_by IS '记录人账号编号';
COMMENT ON COLUMN relations.ledger_gift.created_by_name IS '记录人姓名快照';
COMMENT ON COLUMN relations.ledger_gift.created_at IS '创建时间';
COMMENT ON COLUMN relations.ledger_gift.updated_at IS '最后修改时间';

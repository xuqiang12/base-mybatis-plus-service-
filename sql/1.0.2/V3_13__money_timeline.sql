-- 保存真实操作后的余额快照，不回算或伪造旧流水的历史余额。
CREATE TABLE relations.ledger_money_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  type VARCHAR(16) NOT NULL CHECK(type IN ('income','expense','saving','lend','receive','borrow','pay','transfer','opening')),
  action VARCHAR(10) NOT NULL CHECK(action IN ('create','update','delete')),
  amount_cents BIGINT NOT NULL,
  title VARCHAR(100) NOT NULL,
  note VARCHAR(1000) NOT NULL DEFAULT '',
  flow VARCHAR(250) NOT NULL DEFAULT '',
  total_cents BIGINT NOT NULL,
  savings_cents BIGINT NOT NULL,
  account_cents BIGINT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_ledger_money_log_family_id ON relations.ledger_money_log(family_id, id DESC);

COMMENT ON TABLE relations.ledger_money_log IS '家庭资金操作日志及不可改写的操作后金额快照';
COMMENT ON COLUMN relations.ledger_money_log.id IS '日志编号，按编号倒序分页';
COMMENT ON COLUMN relations.ledger_money_log.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_money_log.type IS '收入、消费、存款、借贷、转账或期初余额';
COMMENT ON COLUMN relations.ledger_money_log.action IS '新增、修改或删除操作';
COMMENT ON COLUMN relations.ledger_money_log.amount_cents IS '本次操作记录的金额，整数分，修改时为修改后的记录金额';
COMMENT ON COLUMN relations.ledger_money_log.title IS '操作时的分类、亲友或账户名称快照';
COMMENT ON COLUMN relations.ledger_money_log.note IS '操作时的备注快照';
COMMENT ON COLUMN relations.ledger_money_log.flow IS '操作时的资金流向说明，保留原账户名称';
COMMENT ON COLUMN relations.ledger_money_log.total_cents IS '操作后的净资产，整数分';
COMMENT ON COLUMN relations.ledger_money_log.savings_cents IS '操作后的总存款，整数分';
COMMENT ON COLUMN relations.ledger_money_log.account_cents IS '操作后的非现金账户余额合计，整数分';
COMMENT ON COLUMN relations.ledger_money_log.created_at IS '实际操作时间，不使用补录的业务日期排序';

-- 一家庭一个月份一张月度记录，月度记录下保存每个分类的合计。
CREATE TABLE relations.ledger_category (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  type VARCHAR(10) NOT NULL CHECK(type IN ('expense', 'income', 'saving')),
  name VARCHAR(100) NOT NULL,
  icon VARCHAR(100) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ledger_category_family ON relations.ledger_category(family_id, type, sort_order);

CREATE TABLE relations.ledger_household_month (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  month_value VARCHAR(7) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(family_id, month_value)
);

CREATE TABLE relations.ledger_household_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month_id BIGINT NOT NULL REFERENCES relations.ledger_household_month(id),
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  category_id BIGINT NOT NULL REFERENCES relations.ledger_category(id),
  type VARCHAR(10) NOT NULL CHECK(type IN ('expense', 'income', 'saving')),
  amount_cents BIGINT NOT NULL CHECK(amount_cents > 0 AND amount_cents <= 9007199254740991),
  note VARCHAR(1000) NOT NULL DEFAULT '',
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  created_by_name VARCHAR(100) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(month_id, category_id)
);

CREATE INDEX idx_ledger_household_item_family ON relations.ledger_household_item(family_id, type);

COMMENT ON TABLE relations.ledger_category IS '家庭收支分类';
COMMENT ON COLUMN relations.ledger_category.id IS '分类编号，自增主键';
COMMENT ON COLUMN relations.ledger_category.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_category.type IS '收入、支出或存款类型';
COMMENT ON COLUMN relations.ledger_category.name IS '分类名称';
COMMENT ON COLUMN relations.ledger_category.icon IS '分类图标';
COMMENT ON COLUMN relations.ledger_category.active IS '是否启用';
COMMENT ON COLUMN relations.ledger_category.sort_order IS '分类顺序';
COMMENT ON COLUMN relations.ledger_category.created_at IS '创建时间';
COMMENT ON COLUMN relations.ledger_category.updated_at IS '最后修改时间';
COMMENT ON TABLE relations.ledger_household_month IS '家庭月度收支记录';
COMMENT ON COLUMN relations.ledger_household_month.id IS '月度记录编号，自增主键';
COMMENT ON COLUMN relations.ledger_household_month.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_household_month.month_value IS '月份，格式 YYYY-MM';
COMMENT ON COLUMN relations.ledger_household_month.created_at IS '创建时间';
COMMENT ON COLUMN relations.ledger_household_month.updated_at IS '最后修改时间';
COMMENT ON TABLE relations.ledger_household_item IS '家庭月度分类合计';
COMMENT ON COLUMN relations.ledger_household_item.id IS '分类合计编号，自增主键';
COMMENT ON COLUMN relations.ledger_household_item.month_id IS '所属月度记录编号';
COMMENT ON COLUMN relations.ledger_household_item.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_household_item.category_id IS '收支分类编号';
COMMENT ON COLUMN relations.ledger_household_item.type IS '收入、支出或存款类型';
COMMENT ON COLUMN relations.ledger_household_item.amount_cents IS '金额，整数分';
COMMENT ON COLUMN relations.ledger_household_item.note IS '备注';
COMMENT ON COLUMN relations.ledger_household_item.created_by IS '记录人账号编号';
COMMENT ON COLUMN relations.ledger_household_item.created_by_name IS '记录人姓名快照';
COMMENT ON COLUMN relations.ledger_household_item.created_at IS '创建时间';
COMMENT ON COLUMN relations.ledger_household_item.updated_at IS '最后修改时间';

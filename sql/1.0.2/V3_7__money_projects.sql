-- 资金项目只记录去向，余额由月收支、借贷和调拨流水计算，不维护重复余额。
CREATE TABLE relations.ledger_money_project (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  type VARCHAR(10) NOT NULL CHECK(type IN ('bank', 'stock', 'other')),
  name VARCHAR(100) NOT NULL,
  note VARCHAR(1000) NOT NULL DEFAULT '',
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ledger_money_project_family ON relations.ledger_money_project(family_id);

CREATE TABLE relations.ledger_money_transfer (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  from_project_id BIGINT REFERENCES relations.ledger_money_project(id),
  to_project_id BIGINT REFERENCES relations.ledger_money_project(id),
  amount_cents BIGINT NOT NULL CHECK(amount_cents > 0 AND amount_cents <= 9007199254740991),
  note VARCHAR(1000) NOT NULL DEFAULT '',
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK(from_project_id IS NOT NULL OR to_project_id IS NOT NULL),
  CHECK(from_project_id <> to_project_id)
);
CREATE INDEX idx_ledger_money_transfer_family ON relations.ledger_money_transfer(family_id);

ALTER TABLE relations.ledger_household_item ADD COLUMN project_id BIGINT REFERENCES relations.ledger_money_project(id);

COMMENT ON TABLE relations.ledger_money_project IS '家庭资金项目';
COMMENT ON COLUMN relations.ledger_money_project.id IS '资金项目编号，自增主键';
COMMENT ON COLUMN relations.ledger_money_project.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_money_project.type IS '项目类型：银行、股票或其他';
COMMENT ON COLUMN relations.ledger_money_project.name IS '项目名称';
COMMENT ON COLUMN relations.ledger_money_project.note IS '项目备注';
COMMENT ON COLUMN relations.ledger_money_project.created_at IS '创建时间';
COMMENT ON TABLE relations.ledger_money_transfer IS '家庭资金调拨流水，不产生收支';
COMMENT ON COLUMN relations.ledger_money_transfer.id IS '调拨编号，自增主键';
COMMENT ON COLUMN relations.ledger_money_transfer.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_money_transfer.from_project_id IS '来源项目，空值表示现金';
COMMENT ON COLUMN relations.ledger_money_transfer.to_project_id IS '目标项目，空值表示现金';
COMMENT ON COLUMN relations.ledger_money_transfer.amount_cents IS '调拨金额，整数分';
COMMENT ON COLUMN relations.ledger_money_transfer.note IS '调拨备注';
COMMENT ON COLUMN relations.ledger_money_transfer.created_by IS '记录人账号编号';
COMMENT ON COLUMN relations.ledger_money_transfer.created_at IS '创建时间';
COMMENT ON COLUMN relations.ledger_household_item.project_id IS '收支资金项目，空值表示现金；旧存款记录不计入资产';

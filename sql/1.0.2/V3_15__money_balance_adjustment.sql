-- 手工校准账户当前余额，不修改账户期初余额或普通收支流水。
CREATE TABLE relations.ledger_money_adjustment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  project_id BIGINT NOT NULL REFERENCES relations.ledger_money_project(id),
  amount_cents BIGINT NOT NULL CHECK(amount_cents <> 0 AND amount_cents >= -9007199254740991 AND amount_cents <= 9007199254740991),
  note VARCHAR(1000) NOT NULL DEFAULT '',
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ledger_money_adjustment_family_project
  ON relations.ledger_money_adjustment(family_id, project_id);

COMMENT ON TABLE relations.ledger_money_adjustment IS '资产账户当前余额校准流水，不修改期初余额';
COMMENT ON COLUMN relations.ledger_money_adjustment.id IS '校准流水编号';
COMMENT ON COLUMN relations.ledger_money_adjustment.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_money_adjustment.project_id IS '被校准的资金项目编号';
COMMENT ON COLUMN relations.ledger_money_adjustment.amount_cents IS '校准差额，正数增加账户余额，负数减少账户余额';
COMMENT ON COLUMN relations.ledger_money_adjustment.note IS '校准备注';
COMMENT ON COLUMN relations.ledger_money_adjustment.created_by IS '记录人账号编号';
COMMENT ON COLUMN relations.ledger_money_adjustment.created_at IS '实际校准时间';

ALTER TABLE relations.ledger_money_log DROP CONSTRAINT IF EXISTS ledger_money_log_type_check;
ALTER TABLE relations.ledger_money_log ADD CONSTRAINT ledger_money_log_type_check
  CHECK(type IN ('income','expense','saving','lend','receive','borrow','pay','transfer','opening','adjustment'));

-- 借贷流水，收款/归还由服务层按家庭和亲友余额校验。
CREATE TABLE relations.ledger_loan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id VARCHAR(80) NOT NULL REFERENCES relations.ledger_family(id),
  direction VARCHAR(10) NOT NULL CHECK(direction IN ('lend', 'borrow', 'receive', 'pay')),
  friend_id BIGINT REFERENCES relations.ledger_friend(id),
  name VARCHAR(100) NOT NULL,
  appellation VARCHAR(100) NOT NULL DEFAULT '',
  amount_cents BIGINT NOT NULL CHECK(amount_cents > 0 AND amount_cents <= 9007199254740991),
  date DATE NOT NULL,
  note VARCHAR(1000) NOT NULL DEFAULT '',
  created_by INTEGER NOT NULL REFERENCES relations.sys_user(id),
  created_by_name VARCHAR(100) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ledger_loan_family_friend ON relations.ledger_loan(family_id, friend_id);

COMMENT ON TABLE relations.ledger_loan IS '借贷流水';
COMMENT ON COLUMN relations.ledger_loan.id IS '借贷流水编号，自增主键';
COMMENT ON COLUMN relations.ledger_loan.family_id IS '所属家庭编号';
COMMENT ON COLUMN relations.ledger_loan.direction IS '借出、收款、借入或归还方向';
COMMENT ON COLUMN relations.ledger_loan.friend_id IS '亲友关联，可空';
COMMENT ON COLUMN relations.ledger_loan.name IS '姓名快照';
COMMENT ON COLUMN relations.ledger_loan.appellation IS '称谓快照';
COMMENT ON COLUMN relations.ledger_loan.amount_cents IS '金额，整数分';
COMMENT ON COLUMN relations.ledger_loan.date IS '业务日期';
COMMENT ON COLUMN relations.ledger_loan.note IS '备注';
COMMENT ON COLUMN relations.ledger_loan.created_by IS '记录人账号编号';
COMMENT ON COLUMN relations.ledger_loan.created_by_name IS '记录人姓名快照';
COMMENT ON COLUMN relations.ledger_loan.created_at IS '创建时间';
COMMENT ON COLUMN relations.ledger_loan.updated_at IS '最后修改时间';

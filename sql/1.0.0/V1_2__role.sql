-- 角色表，由 system-service 管理。
CREATE TABLE relations.sys_role (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

COMMENT ON TABLE relations.sys_role IS '角色表';
COMMENT ON COLUMN relations.sys_role.id IS '角色ID，自增主键';
COMMENT ON COLUMN relations.sys_role.name IS '角色名称，唯一';

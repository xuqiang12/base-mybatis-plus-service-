CREATE SCHEMA IF NOT EXISTS relations;
-- 用户、角色、菜单及操作权限使用独立 schema；不读取或修改原 Node 表。
CREATE TABLE relations.sys_user (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone VARCHAR(30) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    avatar VARCHAR(1000),
    is_super_admin BOOLEAN NOT NULL DEFAULT FALSE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE relations.sys_role (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE relations.sys_permission (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(150) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);
CREATE TABLE relations.sys_menu (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id INTEGER REFERENCES relations.sys_menu(id),
    name VARCHAR(100) NOT NULL,
    path VARCHAR(500),
    component VARCHAR(500),
    icon VARCHAR(100),
    sort INTEGER NOT NULL DEFAULT 0,
    type VARCHAR(20) NOT NULL CHECK (type IN ('DIRECTORY', 'PAGE')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE relations.sys_user_role (
    user_id INTEGER NOT NULL REFERENCES relations.sys_user(id),
    role_id INTEGER NOT NULL REFERENCES relations.sys_role(id),
    PRIMARY KEY (user_id, role_id)
);
CREATE TABLE relations.sys_role_permission (
    role_id INTEGER NOT NULL REFERENCES relations.sys_role(id) ON DELETE CASCADE,
    permission_id INTEGER NOT NULL REFERENCES relations.sys_permission(id),
    PRIMARY KEY (role_id, permission_id)
);
CREATE TABLE relations.sys_menu_role (
    role_id INTEGER NOT NULL REFERENCES relations.sys_role(id) ON DELETE CASCADE,
    menu_id INTEGER NOT NULL REFERENCES relations.sys_menu(id),
    PRIMARY KEY (role_id, menu_id)
);
CREATE TABLE relations.sys_menu_button (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id INTEGER NOT NULL REFERENCES relations.sys_menu(id),
    permission_id INTEGER NOT NULL UNIQUE REFERENCES relations.sys_permission(id),
    name VARCHAR(100),
    sort INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_user_role_role ON relations.sys_user_role(role_id);
CREATE INDEX idx_role_permission_permission ON relations.sys_role_permission(permission_id);
CREATE INDEX idx_menu_role_menu ON relations.sys_menu_role(menu_id);
CREATE INDEX idx_menu_parent ON relations.sys_menu(parent_id);
CREATE INDEX idx_menu_button_menu ON relations.sys_menu_button(menu_id);


-- 菜单表，由 system-service 管理；包含目录和页面菜单。
CREATE TABLE relations.sys_menu (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id INTEGER REFERENCES relations.sys_menu(id),
    name VARCHAR(100) NOT NULL,
    path VARCHAR(500),
    component VARCHAR(500),
    icon VARCHAR(100),
    sort INTEGER NOT NULL DEFAULT 0,
    type VARCHAR(20) NOT NULL CHECK (type IN ('DIRECTORY', 'PAGE')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_menu_parent ON relations.sys_menu(parent_id);

COMMENT ON TABLE relations.sys_menu IS '菜单表';
COMMENT ON COLUMN relations.sys_menu.id IS '菜单ID，自增主键';
COMMENT ON COLUMN relations.sys_menu.parent_id IS '父菜单ID，为空时表示顶级菜单';
COMMENT ON COLUMN relations.sys_menu.name IS '菜单名称';
COMMENT ON COLUMN relations.sys_menu.path IS '前端路由路径';
COMMENT ON COLUMN relations.sys_menu.component IS '前端页面组件标识';
COMMENT ON COLUMN relations.sys_menu.icon IS '菜单图标标识';
COMMENT ON COLUMN relations.sys_menu.sort IS '排序值，升序排列';
COMMENT ON COLUMN relations.sys_menu.type IS '菜单类型：DIRECTORY 目录，PAGE 页面';
COMMENT ON COLUMN relations.sys_menu.created_at IS '创建时间';
COMMENT ON COLUMN relations.sys_menu.updated_at IS '最后更新时间';

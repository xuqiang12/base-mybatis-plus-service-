-- 操作权限表，由 system-service 管理；初始权限数据见 V1_9__seed.sql。
CREATE TABLE relations.sys_permission (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(150) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);

COMMENT ON TABLE relations.sys_permission IS '操作权限表';
COMMENT ON COLUMN relations.sys_permission.id IS '权限ID，自增主键';
COMMENT ON COLUMN relations.sys_permission.code IS '权限编码，唯一，用于接口鉴权';
COMMENT ON COLUMN relations.sys_permission.name IS '权限名称';

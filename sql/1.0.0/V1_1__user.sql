-- 用户账号表，由 system-service 管理；使用独立 schema，不读取或修改原 Node 表。
CREATE SCHEMA IF NOT EXISTS relations;

CREATE TABLE relations.sys_user (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone VARCHAR(30) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    avatar VARCHAR(1000),
    is_super_admin BOOLEAN NOT NULL DEFAULT FALSE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE relations.sys_user IS '用户账号表';
COMMENT ON COLUMN relations.sys_user.id IS '用户ID，自增主键';
COMMENT ON COLUMN relations.sys_user.username IS '用户名，唯一';
COMMENT ON COLUMN relations.sys_user.email IS '邮箱，唯一，可用于登录';
COMMENT ON COLUMN relations.sys_user.phone IS '手机号，唯一，可用于登录';
COMMENT ON COLUMN relations.sys_user.password IS '密码的 BCrypt 散列值';
COMMENT ON COLUMN relations.sys_user.avatar IS '头像地址';
COMMENT ON COLUMN relations.sys_user.is_super_admin IS '是否为超级管理员';
COMMENT ON COLUMN relations.sys_user.is_deleted IS '是否已软删除';
COMMENT ON COLUMN relations.sys_user.deleted_at IS '软删除时间';
COMMENT ON COLUMN relations.sys_user.created_at IS '创建时间';
COMMENT ON COLUMN relations.sys_user.updated_at IS '最后更新时间';

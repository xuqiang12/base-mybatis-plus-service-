-- 菜单按钮表，由 system-service 管理；每个操作权限最多关联一个菜单按钮。
CREATE TABLE relations.sys_menu_button (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id INTEGER NOT NULL REFERENCES relations.sys_menu(id),
    permission_id INTEGER NOT NULL UNIQUE REFERENCES relations.sys_permission(id),
    name VARCHAR(100),
    sort INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_menu_button_menu ON relations.sys_menu_button(menu_id);

COMMENT ON TABLE relations.sys_menu_button IS '菜单按钮表';
COMMENT ON COLUMN relations.sys_menu_button.id IS '菜单按钮ID，自增主键';
COMMENT ON COLUMN relations.sys_menu_button.menu_id IS '所属菜单ID，关联菜单表';
COMMENT ON COLUMN relations.sys_menu_button.permission_id IS '操作权限ID，唯一，关联权限表';
COMMENT ON COLUMN relations.sys_menu_button.name IS '按钮名称';
COMMENT ON COLUMN relations.sys_menu_button.sort IS '排序值，升序排列';
